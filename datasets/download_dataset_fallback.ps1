# Script alternativo para crear dataset de ejemplo - Versión PowerShell
Write-Host "Creando dataset de ejemplo para desarrollo..." -ForegroundColor Green

$DatasetDir = "datasets"
if (!(Test-Path $DatasetDir)) {
    New-Item -ItemType Directory -Path $DatasetDir -Force
}

