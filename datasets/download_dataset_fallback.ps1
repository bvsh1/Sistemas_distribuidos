5,What is machine learning?,Machine learning definition...,It's a subset of AI that enables computers...
6,How to improve coding skills?,Tips for better programming...,Practice regularly and read code...
7,What is distributed systems?,Definition of distributed systems...,Multiple computers working together...
8,Cloud computing benefits?,Advantages of cloud computing...,Scalability and cost reduction...
9,What is API?,API definition and usage...,Application Programming Interface...
10,How to deploy web applications?,Web app deployment steps...,Use platforms like Heroku or AWS...
11,What is JavaScript?,JavaScript programming language...,It's used for web development...
12,How to learn data science?,Data science learning path...,Start with statistics and Python...
13,What is Kubernetes?,Kubernetes container orchestration...,It manages containerized applications...
14,Database types comparison?,SQL vs NoSQL databases...,SQL for structured, NoSQL for unstructured data...
15,What is artificial intelligence?,AI definition and examples...,Machines performing intelligent tasks...
"@

