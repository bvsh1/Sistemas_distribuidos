Write-Host "Dataset de ejemplo creado en: $DatasetDir\sample_yahoo_answers.csv" -ForegroundColor Green
Write-Host "Muestra del dataset:" -ForegroundColor Yellow
Get-Content "$DatasetDir\sample_yahoo_answers.csv" | Select-Object -First 5